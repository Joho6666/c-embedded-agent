function q(
  rpm: [number, number],
  tpm: [number, number],
  dailyReq: [number, number],
  dailyTok: [number, number],
  month: [number, number],
): CredentialQuota {
  return {
    rpmLimit: rpm[1],
    rpmUsed: rpm[0],
    tpmLimit: tpm[1],
    tpmUsed: tpm[0],
    dailyRequestLimit: dailyReq[1],
    dailyRequestUsed: dailyReq[0],
    dailyTokenLimit: dailyTok[1],
    dailyTokenUsed: dailyTok[0],
    monthlyBudget: month[1],
    monthlySpend: month[0],
  };
}

