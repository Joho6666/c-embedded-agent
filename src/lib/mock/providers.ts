import type { Provider } from "@/types";
import { getDescriptor } from "@/descriptors/providers";

function fromDescriptor(
  id: string,
  patch: Partial<Provider> & Pick<Provider, "status" | "credentialCount" | "modelCount" | "requestsToday" | "tokensToday" | "costToday" | "latencyMs" | "successRate">,
): Provider {
  const d = getDescriptor(id)!;
  return {
    id,
    descriptorId: id,
    name: d.name,
    family: d.family,
    color: d.color,
    mark: d.mark,
    local: d.local,
    capabilities: d.capabilities,
    endpoints: d.endpoints,
    authSchemes: d.authSchemes,
    regions: d.regions,
    baseUrl: d.defaultBaseUrl,
    ...patch,
  };
}

