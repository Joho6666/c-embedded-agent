function buildLogs(count: number): RequestLog[] {
  const rand = mulberry32(20260901);
  const logs: RequestLog[] = [];
  for (let i = 0; i < count; i++) {
    const provider = providerPool[Math.floor(rand() * providerPool.length)];
    const model = aliases[Math.floor(rand() * aliases.length)];
    const key = keyPool[Math.floor(rand() * keyPool.length)];
    const fail = rand() > (provider.health === "error" ? 0.82 : provider.health === "degraded" ? 0.96 : 0.985);
    const timeout = fail && rand() > 0.7;
    const prompt = Math.round(180 + rand() * 4200);
    const completion = timeout ? 0 : Math.round(40 + rand() * 1800);
    const latency = Math.round((timeout ? 8000 : 280) + rand() * (fail ? 2400 : 1600));
    const cost = Number(((prompt / 1e6) * 1.2 + (completion / 1e6) * 4.8 + 0.002).toFixed(4));
    logs.push({
      id: `log_${i}`,
      time: iso(i * 47_000 + Math.round(rand() * 20_000)),
      requestId: `req_${(rand() * 1e16).toString(16).slice(0, 12)}`,
      user: users[Math.floor(rand() * users.length)],
      keyId: key.id,
      keyName: key.name,
      model,
      providerId: provider.id,
      promptTokens: prompt,
      completionTokens: completion,
      cost: Math.max(0.004, cost),
      latency,
      status: timeout ? "timeout" : fail ? "error" : "success",
      errorMessage: timeout ? "upstream timeout after 8000ms" : fail ? "upstream 429 rate limited" : undefined,
      endpoint: "/v1/chat/completions",
      stream: rand() > 0.45,
    });
  }
  return logs;
}

